// Build the add-on.
//
//   node scripts/build.mjs          release build → dist/MNInk-v<version>.mnaddon
//   node scripts/build.mjs --dev    adds the hot-reload channel (scripts/dev.mjs)
//
// Output: dist/addon/{main.js,mnaddon.json,logo.png} and the zipped .mnaddon.
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { modules, root } from './assemble.mjs';

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const dev = process.argv.includes('--dev');
const version = pkg.version + (dev ? '-dev' : '');

let js = `// MN Ink ${version} — generated by scripts/build.mjs, edit addon/ instead.\n`;
for (const [name, src] of modules({ dev })) js += `\n// ===== ${name} =====\n` + src;
js = js.replaceAll('__INK_VERSION__', version);

const distDir = path.join(root, 'dist');
const addonDir = path.join(distDir, 'addon');
fs.mkdirSync(addonDir, { recursive: true });

if (dev) {
  const keyFile = path.join(distDir, 'dev-key');
  if (!fs.existsSync(keyFile)) fs.writeFileSync(keyFile, crypto.randomBytes(16).toString('hex'));
  js = js.replace('__DEV_KEY__', fs.readFileSync(keyFile, 'utf8').trim());
}

new Function(js); // syntax check

fs.writeFileSync(path.join(addonDir, 'main.js'), js);
fs.writeFileSync(path.join(addonDir, 'mnaddon.json'), JSON.stringify({
  addonid: 'io.github.jacky1n7.mnink',
  author: 'Jacky1n7',
  title: 'MN Ink',
  version,
  marginnote_version_min: '4.0.0',
  cert_key: ''
}, null, 2) + '\n');
fs.copyFileSync(path.join(root, 'assets', 'logo.png'), path.join(addonDir, 'logo.png'));

for (const f of fs.readdirSync(distDir)) if (f.endsWith('.mnaddon')) fs.rmSync(path.join(distDir, f));
const out = path.join(distDir, `MNInk-v${version}.mnaddon`);
execFileSync('zip', ['-j', '-q', out, ...['main.js', 'mnaddon.json', 'logo.png'].map((f) => path.join(addonDir, f))]);
console.log(`built ${path.relative(root, out)} (${(js.length / 1024).toFixed(0)} KB${dev ? ', dev channel' : ''})`);
